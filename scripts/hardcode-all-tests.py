def escape_jsx(text):
    """Escape special chars for JSX"""
    return text.replace('{', '{{').replace('}', '}}').replace('<', "{'<'}").replace('>', "{'>'}")

# Generate tests array for each page
base_dir = r'C:\Users\Ulagat\FM-Edu\app\courses\mathematics'

for slug, tests in all_tests.items():
    folder_path = os.path.join(base_dir, slug)
    file_path = os.path.join(folder_path, 'page.tsx')

    if not os.path.exists(file_path):
        print(f"⚠️ Файл не найден: {file_path}")
        continue

    # Read existing file
    with open(file_path, 'r', encoding='utf-8') as f:
        content = f.read()

    # Build tests array
    tests_jsx = "  const testQuestions = [\n"
    for test in tests:
        q = escape_jsx(test['q'])
        a = escape_jsx(test['a'])
        tests_jsx += f'    {{ question: "{q}", answer: "{a}" }},\n'
    tests_jsx += "  ];"

    # Replace empty testQuestions array
    pattern = r'const testQuestions = \[\s*\];'
    if re.search(pattern, content):
        content = re.sub(pattern, tests_jsx, content)

        # Write back
        with open(file_path, 'w', encoding='utf-8') as f:
            f.write(content)

        print(f"✅ {slug}: добавлено {len(tests)} тестов")
    else:
        print(f"⚠️ {slug}: не найден паттерн testQuestions")

