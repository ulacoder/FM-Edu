// Generate lesson content for all topics
const lessonsData = {};

topics.forEach(topic => {
  const subjectContent = lessonContent[topic.subject];

  // Try to find matching content by title
  let content = null;
  let youtubeQuery = null;
  let keywords = [];

  if (subjectContent) {
    const matchingKey = Object.keys(subjectContent).find(key =>
      topic.title.toLowerCase().includes(key.toLowerCase()) ||
      key.toLowerCase().includes(topic.title.toLowerCase())
    );

    if (matchingKey) {
      content = subjectContent[matchingKey].content;
      youtubeQuery = subjectContent[matchingKey].youtubeQuery;
      keywords = subjectContent[matchingKey].keywords;
    }
  }

  // Generate generic content if no match found
  if (!content) {
    content = generateGenericContent(topic);
    youtubeQuery = `${topic.title} ${topic.subject} ${topic.grade} класс`;
    keywords = topic.keywords || [];
  }

  lessonsData[topic.id] = {
    topicId: topic.id,
    subject: topic.subject,
    grade: topic.grade,
    quarter: topic.quarter,
    title: topic.title,
    content: content,
    youtubeQuery: youtubeQuery,
    keywords: keywords,
    videoId: null // Will be filled by YouTube API
  };
});

